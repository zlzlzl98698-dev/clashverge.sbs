export function getAllSecondaryTopics(): SecondaryTopic[] {
  return primaryNavSections.flatMap((section) => section.topics);
}

export function getAllTertiaryClusters(): TertiaryCluster[] {
  return getAllSecondaryTopics().flatMap((topic) => topic.clusters);
}

export function getPrimarySectionById(id: string): PrimaryNavSection | undefined {
  return primaryNavSections.find((s) => s.id === id);
}

export function getSecondaryTopic(sectionId: string, slug: string): SecondaryTopic | undefined {
  const section = getPrimarySectionById(sectionId);
  return section?.topics.find((t) => t.slug === slug);
}
